"""
LLM provider protocol.

Defines the interface that all LLM providers (OpenAI, Anthropic, etc.)
must implement to integrate with the VoiceKit pipeline.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, AsyncIterator, Protocol, runtime_checkable


@dataclass
class PipelineContext:
    """Context object passed to the LLM alongside conversation messages.

    Attributes:
        rag_results: Retrieved documents/chunks from a RAG system.
        tool_results: Results from tool/function calls.
        metadata: Arbitrary key-value metadata (call info, user data, etc.).
    """

    rag_results: list[str] | None = None
    tool_results: list[dict[str, Any]] | None = None
    metadata: dict[str, Any] = field(default_factory=dict)


@runtime_checkable
class LLMProvider(Protocol):
    """Abstract interface for a streaming LLM provider.

    An LLM provider generates text responses to conversation messages.
    It streams tokens as they are generated, enabling the TTS layer
    to start synthesizing audio before the full response is complete.
    """

    async def generate(
        self,
        messages: list[dict[str, Any]],
        context: PipelineContext | None = None,
        tools: list[dict[str, Any]] | None = None,
        tool_functions: dict[str, Any] | None = None,
    ) -> AsyncIterator[str]:
        """Stream text tokens for the given conversation.

        Args:
            messages: Conversation history.
            context: Optional pipeline context carrying RAG results.
            tools: Optional list of OpenAI-format tool schemas.
            tool_functions: Optional mapping of tool names to Python callables.

        Yields:
            Text tokens (partial words, words, or phrases) as they
            are generated by the model.
        """
        ...

    # ── Factory methods ──────────────────────────────────────────────

    @classmethod
    def from_openai(
        cls,
        *,
        api_key: str,
        model: str = "gpt-4o-mini",
        system_prompt: str | None = None,
        **kwargs,
    ) -> LLMProvider:
        """Create an OpenAI streaming LLM provider.

        Args:
            api_key: OpenAI API key.
            model: Model name (default: gpt-4o-mini for low latency).
            system_prompt: Optional system prompt prepended to messages.
            **kwargs: Additional options passed to the OpenAI client.
        """
        from backend.llm.openai_provider import OpenAILLM
        return OpenAILLM(
            api_key=api_key,
            model=model,
            system_prompt=system_prompt,
            **kwargs,
        )

    @classmethod
    def from_groq(
        cls,
        *,
        api_key: str,
        model: str = "llama-3.3-70b-versatile",
        system_prompt: str | None = None,
        **kwargs,
    ) -> LLMProvider:
        """Create a Groq streaming LLM provider.

        Args:
            api_key: Groq API key.
            model: Model name (default: llama-3.3-70b-versatile).
            system_prompt: Optional system prompt prepended to messages.
            **kwargs: Additional options passed to the client.
        """
        from backend.llm.groq_provider import GroqLLM
        return GroqLLM(
            api_key=api_key,
            model=model,
            system_prompt=system_prompt,
            **kwargs,
        )
